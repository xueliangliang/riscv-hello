#!/usr/bin/env python3
"""Real U compiler regressions; the identical file also rejects the old source.

--class isolates load-bearing defect classes. All cases run even on a broken
compiler; JSON records actual statuses and every assertion, never a fake pass.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import tempfile

from guest import Guest

spec = importlib.util.spec_from_file_location('compiler_test', Path(__file__).with_name('compiler-test.py'))
assert spec is not None and spec.loader is not None
ct = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ct)
BUILD = Path('build/lesson14')
CONTROL = 'int main(){print_int(9007199254740993);return 19;}\n'

# Expected semantics are language examples, not results generated by the compiler.
INVALID = {
    'lvalue': [
        ('positive-local', 'int x=7; (+x)=42;', 'assignment requires a local lvalue'),
        ('nested-positive', 'int x=7; (+(x))=42;', 'assignment requires a local lvalue'),
        ('positive-chain', 'int x=7; int y=0; y=(+x)=42;', 'assignment requires a local lvalue'),
    ],
    'increment': [
        ('prefix-increment', 'int x=7; ++x;', 'unsupported operator token ++'),
        ('postfix-increment', 'int x=7; print_int(x++ + 1);', 'unsupported operator token ++'),
        ('literal-increment', 'print_int(1++2);', 'unsupported operator token ++'),
        ('adjacent-triple-plus', 'int x=7; print_int(x+++1);', 'unsupported operator token ++'),
    ],
    'decrement': [
        ('prefix-decrement', 'int x=7; --x;', 'unsupported operator token --'),
        ('postfix-decrement', 'int x=7; x--;', 'unsupported operator token --'),
        ('postfix-decrement-expression', 'int x=7; print_int(x-- -1);', 'unsupported operator token --'),
        ('literal-decrement', 'print_int(1--2);', 'unsupported operator token --'),
        ('adjacent-triple-minus', 'int x=7; print_int(x---1);', 'unsupported operator token --'),
    ],
    'initializer': [
        ('read-self', 'int x=x+1;', 'local referenced in its own initializer'),
        ('assign-self', 'int x=(x=42);', 'local referenced in its own initializer'),
        ('shadow-self', 'int x=19; {int x=x+1;}', 'local referenced in its own initializer'),
        ('shadow-assign-self', 'int x=19; {int x=(x=42);}', 'local referenced in its own initializer'),
        ('loop-self', 'int i=0; while(i<3){int x=x+1; print_int(x); i=i+1;}', 'local referenced in its own initializer'),
    ],
    'operators': [
        (f'operator-{index}', f'int x=7; x{operator}1;', f'unsupported operator token {operator}')
        for index, operator in enumerate(('+=', '-=', '*=', '/=', '%=', '<<', '>>', '&&', '||', '&=', '|=', '^=', '->', '##', '...', '<:', ':>', '<%', '%>', '%:', '%:%:', '<<=', '>>='))
    ],
}
VALID = [
    ('values', 'int x=7; int y=0; x=11; ((x))=13; y=x=+17; print_int(x+y); print_int(+ +x); print_int(x + +1); print_int(x - -1); print_int(x + /*comment*/ +1); print_int(- -x); print_int(x+-1); print_int(x-/*comment*/-1);', ['34', '17', '18', '18', '18', '17', '16', '18']),
    ('scope', 'int x=7; {int x=19; print_int(x);} print_int(x); int i=0; while(i<3){int x; print_int(x); x=99; i=i+1;} {int y=x+1; print_int(y);}', ['19', '7', '0', '0', '0', '8']),
    ('wide', 'print_int(9007199254740993+2); print_int(-77/9); print_int(-77%9); print_int(9223372036854775807+1); print_int((-9223372036854775807-1)/-1);', ['9007199254740995', '-8', '-5', '-9223372036854775808', '-9223372036854775808']),
]


def run_actual(guest, command):
    start = len(guest.all)
    output = guest.cmd(command)
    match = re.search(r'exec target=0 result=(\d+)\r?\n', output)
    assert match, output
    pid = int(match[1])
    guest.cmd(f'wait {pid}')
    data = guest.all[start:]
    match = re.search(rb'wait target=%d result=(\d+)\r?\n' % pid, data)
    assert match, data[-3000:]
    status = int(match[1])
    ct.check_execution(data, pid, status)
    return {'pid': pid, 'status': status, 'command': command,
            'transcript': data.decode(errors='replace')}


def require_rejection(record, diagnostic, before, after):
    assert record['status'] == 1, ('expected frontend exit 1', record['status'])
    text = record['transcript']
    assert re.search(r'cc: line 2: ' + re.escape(diagnostic) + r'\r?\n', text), text
    assert 'published native' not in text, text
    assert after['old'] == before['old'], 'FULL existing executable changed'
    assert after['source'] == before['source'], 'FULL source bytes changed'
    assert not after['missing'], 'missing output was created'


def attack_oracle(record, diagnostic, before, after):
    """Mutate actual successful evidence, one claimed invariant at a time."""
    attacks = ('status', 'line', 'diagnostic', 'banner', 'old', 'source', 'missing')
    for attack in attacks:
        changed_record = copy.deepcopy(record)
        changed_after = copy.deepcopy(after)
        if attack == 'status':
            changed_record['status'] = 0
        elif attack == 'line':
            changed_record['transcript'] = record['transcript'].replace('cc: line 2:', 'cc: line 99:')
        elif attack == 'diagnostic':
            changed_record['transcript'] = record['transcript'].replace(diagnostic, 'unrelated diagnostic')
        elif attack == 'banner':
            changed_record['transcript'] += 'cc: published native\r\n'
        elif attack in ('old', 'source'):
            original = after[attack]
            changed_after[attack] = original[:-1] + bytes([original[-1] ^ 1])
        else:
            changed_after['missing'] = True
        try:
            require_rejection(changed_record, diagnostic, before, changed_after)
        except AssertionError:
            continue
        raise AssertionError(f'oracle accepted corrupted {attack} evidence')
    return list(attacks)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--class', dest='category', choices=list(INVALID))
    args = parser.parse_args()
    categories = [args.category] if args.category else list(INVALID)
    label = args.category or 'all'
    records = []
    errors = []
    mutations = {}
    completed = False
    with tempfile.TemporaryDirectory(prefix='lesson14-frontend-', dir=os.environ.get('TMPDIR')) as temporary:
        disk = Path(temporary) / 'disk.img'
        shutil.copyfile(BUILD / 'disk.img', disk)
        boot = disk.read_bytes()[:512*512]
        guest = Guest(f'frontend-{label}-uart.log', str(disk))
        try:
            guest.until('14> ')
            ct.paste(guest, 'control.c', CONTROL)
            for category in categories:
                for index, (name, body, diagnostic) in enumerate(INVALID[category]):
                    # Repair the control via actual cc if an old broken compiler
                    # overwrote it. Each assertion starts from a valid full image.
                    ct.run(guest, './cc control.c old', 0)
                    source = ('int main(){\n' + body + '\nreturn 0;}\n').encode()
                    source_name = f'{category}{index}.c'
                    missing = f'no{category}{index}'
                    ct.paste(guest, source_name, source)
                    before = {'old': ct.content(disk, 'old'), 'source': source}
                    assert ct.content(disk, source_name) == source
                    ct.native_header(before['old'])
                    for output in ('old', missing):
                        record = run_actual(guest, f'./cc {source_name} {output}')
                        state = ct.snapshot(disk)
                        after = {'old': state['files']['old']['content'],
                                 'source': state['files'][source_name]['content'],
                                 'missing': missing in state['files']}
                        record.update(category=category, name=name, output=output,
                                      old_preserved=after['old'] == before['old'],
                                      source_preserved=after['source'] == source,
                                      missing_absent=not after['missing'],
                                      old_sha256=hashlib.sha256(before['old']).hexdigest(),
                                      after_old_sha256=hashlib.sha256(after['old']).hexdigest())
                        try:
                            require_rejection(record, diagnostic, before, after)
                            if category not in mutations:
                                mutations[category] = attack_oracle(record, diagnostic, before, after)
                        except AssertionError as error:
                            record['error'] = str(error)
                            errors.append(f'{category}/{name}/{output}: {error}')
                        records.append(record)
                # A failure must not poison the process lifecycle or filesystem.
                # Compile independent valid cases AFTER each negative defect class.
                for index, (name, body, expected) in enumerate(VALID):
                    source_name = f'ok{category}{index}.c'
                    output = f'ok{category}{index}'
                    ct.paste(guest, source_name, f'int main(){{{body} return 47;}}\n')
                    ct.run(guest, f'./cc {source_name} {output}', 0)
                    ct.native_header(ct.content(disk, output))
                    ct.run(guest, './' + output, 47, expected)
                    records.append({'category': category, 'positive': name, 'expected': expected, 'status': 47})
            guest.cmd('stats', 'value=0x0000000000000000')
            guest.shutdown()
            ct.snapshot(disk)
            assert disk.read_bytes()[:512*512] == boot, 'boot bytes changed'
            completed = True
        finally:
            guest.close()
            result = {'status': 'PASS' if completed and not errors else 'FAIL', 'categories': categories,
                      'negative_compiles': sum('output' in r for r in records),
                      'positive_runs': sum('positive' in r for r in records),
                      'oracle_mutations_rejected': mutations,
                      'errors': errors, 'records': records}
            (BUILD / f'frontend-{label}-results.json').write_text(json.dumps(result, indent=2) + '\n')
    for error in errors:
        print('REJECTED assertion:', error)
    assert not errors, f'{len(errors)} frontend regression assertions failed; see frontend-{label}-results.json'
    print(f'PASS frontend {label}: {result["negative_compiles"]} invalid compiles, {result["positive_runs"]} valid recovery runs; full bytes, clean journal/raw FS, boot and wait/reap checked')


if __name__ == '__main__':
    main()
